#!/usr/bin/env sh
# Rebuilds billing-core.js from the shared billing logic (Parser.gs, Billing.gs) and the contract data.
cd "$(dirname "$0")"
{
  echo "/* Generated by build.sh from shared/Parser.gs, shared/Billing.gs and the rate/facility data. Edit those, not this. */"
  cat shared/Parser.gs shared/Billing.gs
  sed -n '/^var RATE_HEADERS/,/^function setupSheets/p' shared/ContractData.gs | sed '$d'
} > billing-core.js
